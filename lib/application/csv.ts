import { normalizeStored, PORTAL_CSV_HEADERS, portalRow } from "./portal";
import type { Choice, Money, StoredApplication } from "./types";

function cell(value: unknown): string {
  if (value === null || value === undefined) return "";
  const text = Array.isArray(value) ? value.join("; ") : String(value);
  const guarded = /^[=+\-@]/.test(text) ? `'${text}` : text;
  if (/[",\n\r]/.test(guarded)) return `"${guarded.replace(/"/g, '""')}"`;
  return guarded;
}

function choice(prefix: string, value: Choice | null): Record<string, string> {
  return {
    [`${prefix}_option_id`]: value?.option_id ?? "",
    [`${prefix}_other_text`]: value?.other_text ?? "",
  };
}

function money(prefix: string, value: Money | null): Record<string, string | number> {
  return {
    [`${prefix}_amount`]: value?.amount ?? "",
    [`${prefix}_currency`]: value?.currency ?? "",
    [`${prefix}_period`]: value?.period ?? "",
    [`${prefix}_value_state`]: value?.value_state ?? "",
  };
}

